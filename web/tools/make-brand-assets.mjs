// Builds every logo asset from the traced mark (tools/assets/logo-path.json, made by trace-logo.py):
//   components/icons/Logo.tsx                      the React component (takes its colour from `currentColor`)
//   public/assets/brand/logo-stamp-{light,dark}.svg   the mark painted on the home page's 3D orb
//   public/logo-favicon.png                        browser tab icon
//   public/assets/brand/social-card.png            1200x630 share image
// Colours are the site's own: brand blue for light mode, white for dark mode, paper behind.
//
//   python3 tools/trace-logo.py && node tools/make-brand-assets.mjs
import fs from 'node:fs';
import { chromium } from 'playwright';

const { d, width: W, height: H, viewBox } = JSON.parse(fs.readFileSync('tools/assets/logo-path.json', 'utf8'));
const BLUE = '#0000f2'; // --hermes-color-blue
const PAPER = '#f5f5f5'; // --nw-stage
const WHITE = '#fafafe';

fs.mkdirSync('public/assets/brand', { recursive: true });

// 1. the component
fs.writeFileSync(
  'components/icons/Logo.tsx',
  `import type { SVGProps } from 'react';

/**
 * The site's mark: a star above a wave. It is one shape filled with \`currentColor\`, so it follows
 * whatever text colour surrounds it (blue in light mode, white in dark mode).
 * Generated by tools/make-brand-assets.mjs from tools/assets/logo-source.jpg; do not edit by hand.
 */
export function Logo(props: SVGProps<SVGSVGElement>) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="currentColor" {...props}>
      <path d="${d}" />
    </svg>
  );
}

/** Width divided by height of the mark, for sizing it. */
export const LOGO_ASPECT = ${(W / H).toFixed(4)};
`,
);

// 2. the orb stamps: the mark centred on a square canvas
const side = 983;
const stampW = 640;
const k = stampW / W;
const tx = (side - stampW) / 2;
const ty = (side - H * k) / 2;
for (const [theme, fill] of [['light', BLUE], ['dark', '#fff']]) {
  fs.writeFileSync(
    `public/assets/brand/logo-stamp-${theme}.svg`,
    `<svg xmlns="http://www.w3.org/2000/svg" fill="none" width="${side}" height="${side}" viewBox="0 0 ${side} ${side}"><g transform="translate(${tx} ${ty.toFixed(2)}) scale(${k})"><path fill="${fill}" d="${d}"/></g></svg>`,
  );
}

// 3 + 4. raster images, drawn in Chromium
const mark = (color, extra = '') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="${color}" ${extra}><path d="${d}"/></svg>`;
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_PATH ?? ['/opt/pw-browsers/chromium-1194/chrome-linux/chrome'].find((p) => fs.existsSync(p)),
});
const page = await browser.newPage();

await page.setViewportSize({ width: 96, height: 96 });
await page.setContent(`<body style="margin:0;background:${BLUE};display:grid;place-items:center;width:96px;height:96px">${mark(WHITE, 'width="68"')}</body>`);
await page.screenshot({ path: 'public/logo-favicon.png' });

await page.setViewportSize({ width: 1200, height: 630 });
await page.setContent(`<body style="margin:0;background:${BLUE};display:grid;place-items:center;width:1200px;height:630px">${mark(WHITE, 'width="560"')}</body>`);
await page.screenshot({ path: 'public/assets/brand/social-card.png' });
await browser.close();
console.log('wrote Logo.tsx, orb stamps, favicon and social card');
